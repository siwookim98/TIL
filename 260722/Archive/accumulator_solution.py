"""
빈 변수 만들기 + 2차원 배열 + 2중 for + 조건문
==========================================================
오늘의 목표 4가지:
    1) 반복을 돌리기 '전에' 빈 변수를 스스로 만든다. (빈 상자를 먼저 준비한다)
    2) 2차원 배열을 단순한 2중 for + 조건문으로 훑는다.
    3) 최소 2바퀴(=행이 한 번 넘어가는 순간까지)는 종이에 손으로 그린다.
    4) 계속 print로 확인하며 진행한다.

핵심 비유 -- '빈 상자':
    빈 리스트 [] 를 만드는 건 책상에 '빈 상자'를 먼저 올려두는 것.
    반복문을 돌면서 조건에 맞는 물건만 이 상자에 하나씩 담는다.
    반복이 끝나면 상자 안에 결과가 모여 있다.

예제 데이터 (2행 3열):
        열(j) ->   0    1    2
    행(i) 0        1    2    3
    행(i) 1        4    5    6
"""

matrix = [
    [1, 2, 3],
    [4, 5, 6],
]


# =============================================================================
# 예시 1) 2차원 배열 전체 순회 -- i(행), j(열)로 모든 칸을 방문한다
# =============================================================================
def example_1_visit_all():
    print('===== 예시 1) 전체 순회 =====')

    for i in range(len(matrix)):            # 바깥: 행 번호 (0, 1)
        for j in range(len(matrix[i])):     # 안쪽: 열 번호 (0, 1, 2)
            print(f'matrix[{i}][{j}] = {matrix[i][j]}')

    # [포인트]
    #   i=0에서 j가 0,1,2 를 다 돈 뒤 i=1로 넘어가는 순간,
    #   j가 '다시 0'으로 리셋된다. <- 이 전환을 손으로 확인시킨다.


# =============================================================================
# 예시 2) 빈 리스트를 만들어 '짝수만' 골라 담기 (누적 패턴)
# =============================================================================
def example_2_accumulate():
    print('===== 예시 2) 빈 리스트에 쌓기 =====')

    # [핵심] 반복 '전에' 빈 상자를 스스로 만든다
    evens = []

    for i in range(len(matrix)):
        for j in range(len(matrix[i])):
            value = matrix[i][j]
            if value % 2 == 0:       # 조건: 짝수만
                evens.append(value)  # 누적: 상자에 담기

    print(evens)  # 반복이 끝나면 상자 안에 결과가 모여 있다

    # [포인트]
    #   evens 는 빈 [] 에서 시작해 [2] -> [2, 4] -> [2, 4, 6] 으로 커진다.
    #   "빈 변수를 먼저 만들지 않으면 담을 곳이 없다"를 강조한다.


# =============================================================================
# 예시 3) print 검산 -- 상자(evens)가 채워지는 과정을 눈으로 본다
# =============================================================================
def example_3_print_debugging():
    print('===== 예시 3) print 검산 =====')

    evens = []
    print(f'[확인] 시작할 때 evens = {evens}')  # 빈 상자 상태 확인

    for i in range(len(matrix)):
        # [확인용] 새 행 진입 = j가 0으로 리셋되는 순간
        print(f'[확인] {i}번 행 진입 -> j를 0부터 다시 시작')

        for j in range(len(matrix[i])):
            value = matrix[i][j]
            # [확인용] 매 칸의 i, j, value 를 손 추적표와 대조한다
            print(f'[확인]    i={i}, j={j}, value={value}')

            if value % 2 == 0:
                evens.append(value)
                # [확인용] 담은 직후 상자 상태 -> 상자가 커지는 게 눈에 보인다
                print(f'[확인]    -> 짝수! evens = {evens}')

    print(f'최종 결과: {evens}')

    # [포인트]
    #   append 직후마다 evens 를 찍으면 '상자가 채워지는 순간'이 그대로 보인다.
    #   다 이해했으면 [확인] 줄만 지우면 완성.


